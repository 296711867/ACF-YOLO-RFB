"""Build a sanitized public-release copy of the repository.

The public release is derived exclusively from Git-tracked files, so ignored
artifacts (runs/, data/, checkpoints, large prediction JSONLs) never enter it.
On top of that:

1. Internal-only tracked files are excluded (docs/internal/, internal
   deliberation drafts).
2. Server-specific absolute paths are scrubbed from text files.
3. A keyword gate scans every copied file (binary-safe) and fails the build on
   any remaining identity leak, while softer patterns only raise warnings for
   manual review.
4. README passages that only apply to the internal layout are patched.
5. The export is initialized as a fresh Git repository with a single initial
   commit; the internal history stays in .project.git.

See docs/OPEN_SOURCE_RELEASE.md for the release manual. Run:

    python scripts/build_public_release.py [--output public_release] [--dry-run]
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROJECT_GIT_DIR = ROOT / ".project.git"

# Tracked files that must never enter the public release.
PUBLIC_EXCLUSIONS = (
    "docs/internal/",
    "docs/paper/archive/THESIS_CONTRIBUTION_ASSESSMENT.md",
)

# Internal identity tokens are assembled from fragments so that the published
# copy of this script does not itself contain the literal patterns it scrubs.
_INTERNAL_USER = "bbt" "gpu"
_INTERNAL_PROJECT = "lingbot-" "depth"
_HOME_PREFIX = "/home/" + _INTERNAL_USER
_PROJECT_PREFIX = _HOME_PREFIX + "/code/github-project/" + _INTERNAL_PROJECT

# Ordered text replacements applied to every UTF-8 file (longest first).
PATH_SCRUB_RULES = (
    (_PROJECT_PREFIX + "/yolo", "<REPO_ROOT>"),
    (_PROJECT_PREFIX, "<PROJECTS_ROOT>"),
    (_HOME_PREFIX + "/miniconda3", "<CONDA_HOME>"),
    (_HOME_PREFIX, "<HOME>"),
    # Catch-all for non-path tokens (e.g. hostname fields); path forms are
    # already consumed by the rules above.
    (_INTERNAL_USER, "<HOST_USER>"),
)

# Any remaining occurrence fails the build (identity leaks).
HARD_FAIL_PATTERNS = (_INTERNAL_USER, _INTERNAL_PROJECT)

# Occurrences are listed for manual review but do not fail the build.
REVIEW_PATTERNS = ("/home/", "miniconda3", "导师", "授权启动", "用户决定")

# README passages that describe internal-only layout; replaced on export.
README_INTERNAL_TREE_LINE = "docs/internal/  内部会话交接与工作记录（不参与公开发布）\n"
README_GIT_BLOCK = """根项目的真实 Git 目录是 `.project.git`；普通 Git 命令只在 `.worktrees/*` 开发工作树内直接可用：

```bash
git --git-dir=.project.git --work-tree=. status
git --git-dir=.project.git --work-tree=. log --oneline -5
```
"""
README_GIT_BLOCK_PUBLIC = """本仓库是研究工程的公开发布快照（由 `scripts/build_public_release.py` 从内部审计库导出，单提交历史）；完整实验过程历史保存在内部审计仓库中。
"""


def git(*args: str) -> str:
    """Run Git against the alternate repository or the current standard worktree."""
    command = (
        ["git", f"--git-dir={PROJECT_GIT_DIR}", f"--work-tree={ROOT}", *args]
        if PROJECT_GIT_DIR.is_dir()
        else ["git", "-C", str(ROOT), *args]
    )
    return subprocess.run(command, check=True, capture_output=True, text=True).stdout


def tracked_files() -> list[str]:
    """Return repository-relative tracked file paths."""
    return [line.strip() for line in git("ls-files").splitlines() if line.strip()]


def is_excluded(relative: str) -> bool:
    """Return whether one tracked file is internal-only."""
    normalized = relative.replace("\\", "/")
    return any(
        normalized == exclusion.rstrip("/") or normalized.startswith(exclusion)
        for exclusion in PUBLIC_EXCLUSIONS
    )


def scrub_text(raw: bytes) -> tuple[bytes, bool]:
    """Apply path scrubbing to one file's bytes; return (content, changed)."""
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw, False
    for needle, replacement in PATH_SCRUB_RULES:
        text = text.replace(needle, replacement)
    scrubbed = text.encode("utf-8")
    return scrubbed, scrubbed != raw


def patch_readme(text: str) -> str:
    """Adapt the repository README to the public snapshot layout."""
    if README_INTERNAL_TREE_LINE not in text:
        print("WARNING: README internal tree line not found for patching")
    text = text.replace(README_INTERNAL_TREE_LINE, "")
    if README_GIT_BLOCK not in text:
        print("WARNING: README git block not found for patching")
    return text.replace(README_GIT_BLOCK, README_GIT_BLOCK_PUBLIC)


def public_gitignore(text: str) -> str:
    """Drop internal-only ignore rules from the exported .gitignore."""
    dropped = {
        ".project.git/",
        ".worktrees/",
        "public_release/",
        "# Public release export (generated by scripts/build_public_release.py)",
    }
    return "\n".join(line for line in text.splitlines() if line.strip() not in dropped) + "\n"


def scan_gate(haystack: bytes) -> tuple[list[str], list[str]]:
    """Return (hard failures, review warnings) found in one file's bytes."""
    hard = [pattern for pattern in HARD_FAIL_PATTERNS if pattern.encode() in haystack]
    review = [pattern for pattern in REVIEW_PATTERNS if pattern.encode() in haystack]
    return hard, review


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="public_release", help="export directory name under the repo root")
    parser.add_argument("--dry-run", action="store_true", help="list planned actions without copying")
    parser.add_argument(
        "--commit-message",
        default="Initial public release of the YOLO26 road small-object detection research repository",
        help="initial commit message for the exported repository",
    )
    args = parser.parse_args()

    files = tracked_files()
    copied = [path for path in files if not is_excluded(path)]
    excluded = [path for path in files if is_excluded(path)]
    print(f"Tracked files: {len(files)}; copied: {len(copied)}; internal-only excluded: {len(excluded)}")
    for path in excluded:
        print(f"  excluded: {path}")

    target = ROOT / args.output
    if args.dry_run:
        scrub_candidates = 0
        for relative in copied:
            source = ROOT / relative
            if not source.is_file():
                continue
            content, changed = scrub_text(source.read_bytes())
            if changed:
                scrub_candidates += 1
        print(f"Dry run complete: {scrub_candidates} text files would be scrubbed; output: {target}")
        return 0

    if target.exists():
        print(f"ERROR: output directory already exists: {target}")
        return 1
    target.mkdir(parents=True)

    scrubbed_count = 0
    review_hits: list[str] = []
    hard_failures: list[str] = []
    for relative in copied:
        source = ROOT / relative
        if not source.is_file():
            print(f"WARNING: tracked file missing on disk, skipped: {relative}")
            continue
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        raw = source.read_bytes()
        content, changed = scrub_text(raw)
        normalized = relative.replace("\\", "/")
        if normalized == "README.md":
            content = patch_readme(content.decode("utf-8")).encode("utf-8")
            changed = True
        elif normalized == ".gitignore":
            content = public_gitignore(source.read_text(encoding="utf-8")).encode("utf-8")
            changed = True
        destination.write_bytes(content)
        if changed:
            scrubbed_count += 1
        hard, review = scan_gate(content)
        if hard:
            hard_failures.append(f"{relative}: {', '.join(hard)}")
        if review:
            review_hits.append(f"{relative}: {', '.join(review)}")

    print(f"Copied {len(copied)} files; scrubbed/patched {scrubbed_count}.")
    if review_hits:
        print(f"\nReview-pattern occurrences ({len(review_hits)} files) — check before publishing:")
        for line in review_hits:
            print(f"  {line}")
    if hard_failures:
        print(f"\nGATE FAILED — identity patterns remain in {len(hard_failures)} files:")
        for line in hard_failures:
            print(f"  {line}")
        return 1

    git_env = (
        ["git", f"--git-dir={PROJECT_GIT_DIR}", f"--work-tree={ROOT}"]
        if PROJECT_GIT_DIR.is_dir()
        else ["git", "-C", str(ROOT)]
    )
    internal_head = subprocess.run(
        git_env + ["rev-parse", "HEAD"], check=True, capture_output=True, text=True
    ).stdout.strip()
    subprocess.run(["git", "-C", str(target), "init", "-q"], check=True)
    report = target / "_BUILD_REPORT.md"
    report.write_text(
        "\n".join(
            [
                "# Public release build report",
                "",
                f"Source commit: {internal_head}",
                f"Files copied: {len(copied)}; internal-only excluded: {len(excluded)}",
                f"Scrubbed/patched text files: {scrubbed_count}",
                f"Hard-gate result: passed (internal user/project tokens absent)",
                f"Review-pattern files: {len(review_hits)}",
                "",
                "This file is excluded from the exported Git history via .git/info/exclude.",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    info_exclude = target / ".git" / "info" / "exclude"
    info_exclude.parent.mkdir(parents=True, exist_ok=True)
    info_exclude.write_text("_BUILD_REPORT.md\n", encoding="utf-8")
    subprocess.run(["git", "-C", str(target), "add", "."], check=True)
    shell_scripts = subprocess.run(
        ["git", "-C", str(target), "ls-files", "*.sh"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.split()
    if shell_scripts:
        subprocess.run(
            ["git", "-C", str(target), "update-index", "--chmod=+x", *shell_scripts],
            check=True,
        )
    subprocess.run(
        [
            "git",
            "-C",
            str(target),
            "-c",
            "user.name=YOLO26-SDF Public Release",
            "-c",
            "user.email=yolo26-sdf@localhost",
            "commit",
            "-q",
            "-m",
            f"{args.commit_message}\n\nExported from internal audit repository at {internal_head}.",
        ],
        check=True,
    )
    info_exclude = target / ".git" / "info" / "exclude"
    info_exclude.parent.mkdir(parents=True, exist_ok=True)
    info_exclude.write_text("_BUILD_REPORT.md\n", encoding="utf-8")
    print(f"\nPublic release ready: {target}")
    print(f"Exported from internal commit {internal_head}; single-commit history initialized.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
